""" a program that will convert Celcius to Fahrenheit"""

#taking the temperature in Celcius from the User
TemperatureCelcius=float(input("Enter your desired temperature in Celcius "))

#converting the temperature to Fahrenheit and displaying the result
TemperatureFahrenheit=(TemperatureCelcius*1.8)+32
print("The temperature has been converted to Fahrenheit")
print("The temperature in Fahrenheit is ", TemperatureFahrenheit)
